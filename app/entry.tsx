import React from 'react';
import {createRoot} from 'react-dom/client';
import Home from './page';
import Community from './community';
import Profile from './profile';
import {AuthProvider} from './auth';
import RequirementForm from './requirements';
import Messages from './messages';
import './globals.css';
const page=new URLSearchParams(window.location.search).get('page');
document.title=page==='me'?'我的主页 · 恣优 FlowIn':page==='community'?'人才社区 · 恣优 FlowIn':'恣优 FlowIn · 项目机会发现平台';
const path=window.location.pathname;
const profileMatch=path.match(/^\/profile\/([0-9a-f-]+)\/?$/i),messageMatch=path.match(/^\/messages(?:\/([0-9a-f-]+))?\/?$/i);
const content=profileMatch?<Profile userId={profileMatch[1]}/>:path==='/requirements/new'?<RequirementForm/>:messageMatch?<Messages conversationId={messageMatch[1]}/>:page==='me'?<Profile/>:page==='community'?<Community/>:<Home/>;
createRoot(document.getElementById('root')!).render(<AuthProvider>{content}</AuthProvider>);
