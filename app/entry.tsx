import React from 'react';
import {createRoot} from 'react-dom/client';
import Home from './page';
import Community from './community';
import Profile from './profile';
import {AuthProvider} from './auth';
import RequirementForm from './requirements';
import Messages from './messages';
import About from './about';
import EventDetail from './event-detail';
import './globals.css';
const params=new URLSearchParams(window.location.search),page=params.get('page');
document.title=page==='me'?'我的主页 · 恣优 FlowIn':page==='community'?'人才社区 · 恣优 FlowIn':page==='about'?'关于我们 · 恣优 FlowIn':'恣优 FlowIn · 项目机会发现平台';
const path=window.location.pathname;
const profileMatch=path.match(/^\/profile\/([0-9a-f-]+)\/?$/i),messageMatch=path.match(/^\/messages(?:\/([0-9a-f-]+))?\/?$/i);
const profileId=profileMatch?.[1]||(page==='profile'?params.get('user'):null),conversationId=messageMatch?.[1]||(page==='messages'?params.get('conversation'):null),eventId=page==='event'?params.get('id'):null;
const content=eventId?<EventDetail eventId={eventId}/>:profileId?<Profile userId={profileId}/>:path==='/requirements/new'||page==='publish'?<RequirementForm/>:messageMatch||page==='messages'?<Messages conversationId={conversationId??undefined}/>:page==='me'?<Profile/>:page==='community'?<Community/>:page==='about'?<About/>:<Home/>;
createRoot(document.getElementById('root')!).render(<AuthProvider>{content}</AuthProvider>);
